let total = 0;
FILES.forEach(f => {
  const p = path.join(__dirname, '..', f);
  if (!fs.existsSync(p)) { console.log('skip ' + f); return; }
  let src = fs.readFileSync(p, 'utf8');
  let n = 0;
  MAP.forEach(([a, b]) => {
    if (a === b) return;
    let c = 0;
    src = src.split(a).join(b);
    c = 1;
    if (c) n++;
  });
  // 二次清理：年/岁 前的多余空格
  src = src.replace(/(\d)\s+年/g, '$1 年');
  src = src.replace(/年\s+·/g, '年 ·');
  fs.writeFileSync(p, src, 'utf8');
  total += n;
  console.log(f + ' done');
});
